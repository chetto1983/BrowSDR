// Writes src/client/worker/decoders/digimode/lora-sat/satnogs.ts: the LoRa transmitters SatNOGS DB lists for the
// satellites in TinyGS's element file. Usage:
//   node scripts/tinygs/satnogs-lora.mjs <transmitters.json> <tinygs_supported.txt> [YYYY-MM-DD]
//   npx prettier --write src/client/worker/decoders/digimode/lora-sat/satnogs.ts
// transmitters.json is the full list of https://db.satnogs.org/api/transmitters/?format=json (SatNOGS DB data are
// CC BY-SA 4.0, so the file written is too); tinygs_supported.txt is https://api.tinygs.com/v1/tinygs_supported.txt.
// Nothing is fetched here: download both first. Only SatNOGS's own fields are kept; nothing is added or guessed.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
const out = path.join(root, 'src/client/worker/decoders/digimode/lora-sat/satnogs.ts');
const [txPath, tlePath, date = new Date().toISOString().slice(0, 10)] = process.argv.slice(2);
if (!txPath || !tlePath) {
	console.error('Usage: node scripts/tinygs/satnogs-lora.mjs <transmitters.json> <tinygs_supported.txt> [YYYY-MM-DD]');
	process.exit(2);
}

const ALPHA5 = 'ABCDEFGHJKLMNPQRSTUVWXYZ';
/** NORAD number of TLE line 1, Alpha-5 (a letter for the ten-thousands from 100000 up) included. */
function norad(field) {
	const head = field[0];
	return /[A-Z]/.test(head) ? (ALPHA5.indexOf(head) + 10) * 10000 + Number(field.slice(1)) : Number(field);
}

const lines = (await fs.readFile(tlePath, 'utf8')).split(/\r?\n/).map((line) => line.trimEnd());
const names = new Map();
for (let i = 0; i + 2 < lines.length; i++) {
	if (!lines[i + 1].startsWith('1 ') || !lines[i + 2].startsWith('2 ')) continue;
	const id = norad(lines[i + 1].slice(2, 7));
	names.set(id, [...(names.get(id) ?? []), lines[i].trim()]);
	i += 2;
}
const transmitters = JSON.parse(await fs.readFile(txPath, 'utf8'));
const rows = transmitters
	.filter((t) => t.mode === 'LoRa' && names.has(t.norad_cat_id) && t.downlink_low)
	.map((t) => ({
		norad: t.norad_cat_id,
		names: names.get(t.norad_cat_id),
		description: t.description,
		freqMHz: t.downlink_low / 1e6,
		bwHz: t.baud ? Math.round(t.baud * 10) / 10 : 0,
		alive: !!t.alive && t.status === 'active',
		unconfirmed: !!t.unconfirmed,
		updated: String(t.updated).slice(0, 10),
	}))
	.sort((a, b) => a.norad - b.norad || a.freqMHz - b.freqMHz);

const body = rows.map((r) => `\t${JSON.stringify(r).replace(/"(\w+)":/g, '$1: ')},`).join('\n');
const source = `// SPDX-FileCopyrightText: SatNOGS DB contributors, Libre Space Foundation
// SPDX-License-Identifier: CC-BY-SA-4.0
// Generated by scripts/tinygs/satnogs-lora.mjs on ${date}; do not edit by hand.
// Source: SatNOGS DB, https://db.satnogs.org (the transmitters API), data licensed under CC BY-SA 4.0
// (https://creativecommons.org/licenses/by-sa/4.0/); this selection is shared under the same licence. Selected: the
// transmitters SatNOGS lists with mode "LoRa" for the ${names.size} satellites (by NORAD number) of TinyGS's element file
// (https://api.tinygs.com/v1/tinygs_supported.txt, read the same day), with SatNOGS's description, downlink, "baud"
// (where SatNOGS puts a LoRa transmitter's bandwidth, in Hz), status and date. The names are TinyGS's. Unverified:
// nothing here was checked against a real signal by BrowSDR.

import type { SatnogsLoraTransmitter } from './types';

/** SatNOGS DB's LoRa transmitters of the satellites TinyGS supports (${rows.length} transmitters, ${new Set(rows.map((r) => r.norad)).size} satellites). */
export const SATNOGS_LORA: readonly SatnogsLoraTransmitter[] = [
${body}
];

/** Where the table comes from, for the panels. */
export const SATNOGS_LORA_SOURCE = 'SatNOGS DB (db.satnogs.org), CC BY-SA 4.0, read ${date}';
`;
await fs.writeFile(out, source);
console.log(
	`${rows.length} LoRa transmitters of ${new Set(rows.map((r) => r.norad)).size} satellites written to ${path.relative(root, out)}`,
);
