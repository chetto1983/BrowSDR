const utf8 = new TextDecoder('utf-8');

/** UCS-2 big endian; a high surrogate followed by a low one is combined (UTF-16 sent as "UCS-2"). */
function ucs2be(p: Uint8Array): string {
	let s = '';
	for (let i = 0; i + 1 < p.length; i += 2) s += String.fromCharCode((p[i] << 8) | p[i + 1]);
	return s;
}

/** DAB charset field (FIG 1, dynamic label): 0 EBU Latin, 4 ISO 8859-1, 6 UCS-2, 15 UTF-8; anything else as EBU Latin. */
export function dabCharset(charset: number, p: Uint8Array): string {
	if (charset === 6) return ucs2be(p);
	if (charset === 15) return utf8.decode(p);
	let s = '';
	for (const b of p) s += String.fromCharCode(charset === 4 ? b : EBU_LATIN[b]);
	return s;
}

function invisible(c: number): boolean {
	return (
		c < 0x20 ||
		(c >= 0x7f && c <= 0x9f) ||
		c === 0xad ||
		(c >= 0x200b && c <= 0x200f) ||
		(c >= 0x2028 && c <= 0x202e) ||
		(c >= 0x2060 && c <= 0x206f) ||
		c === 0xfeff ||
		c === 0xfffd ||
		c === 0xfffe ||
		c === 0xffff ||
		(c >= 0xd800 && c <= 0xdfff) ||
		(c >= 0xfff9 && c <= 0xfffb)
	);
}

const SPACES = new Set([9, 10, 13, 0x8a, 0x2028, 0x2029, 0xa0, 0x3000]);

/** No control or invisible characters (tabs, line breaks, NBSP become spaces), runs of spaces folded to one, trimmed. */
export function clean(text: string): string {
	let out = '';
	let space = false;
	for (const ch of text) {
		const c = ch.codePointAt(0) ?? 0;
		if (c === 0x20 || SPACES.has(c)) {
			space = out.length > 0;
			continue;
		}
		if (invisible(c)) continue;
		if (space) out += ' ';
		space = false;
		out += ch;
	}
	return out;
}

/** A label in the given charset to clean text. */
export function labelText(charset: number, p: Uint8Array): string {
	return clean(dabCharset(charset, p));
}
